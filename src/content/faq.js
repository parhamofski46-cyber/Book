/** همه‌ی پرسش‌ها در یک آرایه‌ی صاف — برای داده‌ی ساختاریافته */
function allItems() {
  return GROUPS.reduce((acc, g) => acc.concat(g.items), []);
}

/**
 * پرسش‌های منتخب برای صفحه‌هایی که جای کم دارند (مثل «تماس با ما»).
 * عمداً از گروه‌های مختلف انتخاب شده‌اند تا مشتری تصویر کاملی بگیرد.
 */
const HIGHLIGHT = [
  ['price', 0],
  ['delivery', 0],
  ['forge', 0],
  ['galvanized', 0],
  ['shop', 0],
];

function highlights() {
  return HIGHLIGHT.map(([id, i]) => {
    const g = GROUPS.find((x) => x.id === id);
    return g ? g.items[i] : null;
  }).filter(Boolean);
}

/**
 * داده‌ی ساختاریافته‌ی FAQPage.
 *
 * این یکی از کم‌هزینه‌ترین و مؤثرترین کارهای سئوست: گوگل پرسش‌ها را
 * می‌تواند مستقیم زیر نتیجه‌ی سایت نشان بدهد و سهم فضای شما در صفحه‌ی
 * نتایج چند برابر می‌شود.
 *
 * @param {Array} items زوج‌های [پرسش، پاسخ]
 */
function faqSchema(items) {
  return {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: items.map((f) => ({
      '@type': 'Question',
      name: f[0],
      acceptedAnswer: { '@type': 'Answer', text: f[1] },
    })),
  };
}

module.exports = { GROUPS, allItems, highlights, faqSchema };
