/**
 * راهنمای یک دسته را برمی‌گرداند، یا null اگر نداشته باشد.
 *
 * تطبیق انعطاف‌پذیر است چون نام دسته در دیتابیس ممکن است پسوند داشته باشد
 * (مثل «ورق گالوانیزه (تولید خودمان)») یا مالک بعداً کمی تغییرش بدهد.
 */
function guideFor(categoryName) {
  const name = String(categoryName || '').trim();
  if (!name) return null;
  if (GUIDES[name]) return GUIDES[name];

  const key = Object.keys(GUIDES).find(
    (k) => name.indexOf(k) === 0 || k.indexOf(name) === 0
  );
  return key ? GUIDES[key] : null;
}

module.exports = { guideFor, GUIDES };
