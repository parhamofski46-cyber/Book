/**
 * انتخاب آیکون مناسب بر اساس نام دسته‌بندی.
 * چون مدیر می‌تواند دسته‌ی جدید بسازد، بر اساس کلمات کلیدی نام تشخیص داده
 * می‌شود و اگر چیزی پیدا نشد، آیکون عمومی برمی‌گردد.
 */
function categoryIcon(name) {
  const n = String(name || '');
  if (/فرفورژه|گل|طرح/.test(n)) return 'scroll';
  if (/قوطی|پروفیل/.test(n) && !/نبشی/.test(n)) return 'tube';
  if (/نبشی|پروفیل/.test(n)) return 'angle';
  if (/رابیتس|توری|مش/.test(n)) return 'mesh';
  if (/گوزن|حفاظ|شاخ/.test(n)) return 'spikes';
  if (/فنس|حصار/.test(n)) return 'fence';
  if (/ایزوگام|قیر|عایق/.test(n)) return 'roll';
  if (/میلگرد|تیرآهن|ورق/.test(n)) return 'layers';
  return 'box';
}

/**
 * ساخت تگ SVG یک آیکون.
 * @param {string} name نام آیکون
 * @param {string} className کلاس CSS
 */
function icon(name, className = 'ico') {
  const d = paths[name];
  if (!d) return '';
  const attrs =
    name === 'arrow'
      ? 'fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"'
      : 'fill="currentColor"';
  return `<svg class="${className}" viewBox="0 0 24 24" aria-hidden="true" ${attrs}><path d="${d}"/></svg>`;
}

