// ------------------------------------------------------ توابع درج

const insertCategory = db.prepare(
  'INSERT INTO categories (slug, name, description, sort_order, is_featured) VALUES (?, ?, ?, ?, ?)'
);
const insertSubcategory = db.prepare(
  'INSERT INTO subcategories (category_id, slug, name, sort_order) VALUES (?, ?, ?, ?)'
);
const insertProduct = db.prepare(
  `INSERT INTO products (slug, name, category_id, subcategory_id, summary, description,
                         price_text, unit, in_stock, sort_order)
   VALUES (@slug, @name, @category_id, @subcategory_id, @summary, @description,
           @price_text, @unit, 1, @sort_order)`
);

function seedCatalog() {
  const already = db.prepare('SELECT COUNT(*) n FROM categories').get().n;
  if (already > 0) return false; // قبلاً پر شده — دست نمی‌زنیم

  const run = db.transaction(() => {
    CATEGORIES.forEach((cat, ci) => {
      const catSlug = slugify(cat.name);
      const { lastInsertRowid: catId } = insertCategory.run(
        catSlug,
        cat.name,
        cat.description,
        ci,
        cat.featured || 0
      );

      const subIds = {};
      (cat.subcategories || []).forEach((sub, si) => {
        const { lastInsertRowid: subId } = insertSubcategory.run(
          catId,
          slugify(sub.name),
          sub.name,
          si
        );
        subIds[sub.name] = subId;
      });

      (cat.products || []).forEach((p, pi) => {
        insertProduct.run({
          slug: slugify(p.name),
          name: p.name,
          category_id: catId,
          subcategory_id: p.sub ? subIds[p.sub] || null : null,
          summary: p.summary || '',
          description: p.description || '',
          price_text: 'استعلام قیمت روز',
          unit: p.unit || '',
          sort_order: pi,
        });
      });
    });
  });

  run();
  return true;
}

// ------------------------------------------------- کاربر پیش‌فرض پنل

function seedAdmin() {
  const exists = db.prepare('SELECT COUNT(*) n FROM admins').get().n;
  if (exists > 0) return null;

  const username = process.env.ADMIN_USERNAME || 'admin';
  const password = process.env.ADMIN_PASSWORD || 'foolad1234';
  const mustChange = process.env.ADMIN_PASSWORD ? 0 : 1;

  db.prepare('INSERT INTO admins (username, password_hash, must_change) VALUES (?, ?, ?)').run(
    username,
    bcrypt.hashSync(password, 12),
    mustChange
  );

  return { username, password, mustChange };
}

