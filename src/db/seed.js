function seedTestimonials() {
  const already = db.prepare('SELECT COUNT(*) n FROM testimonials').get().n;
  if (already > 0) return false;

  const insert = db.prepare(
    'INSERT INTO testimonials (name, city, job, text, rating, sort_order) VALUES (?, ?, ?, ?, ?, ?)'
  );
  SAMPLE_TESTIMONIALS.forEach((t, i) => {
    insert.run(t.name, t.city, t.job, t.text, t.rating, i);
  });
  return true;
}

/** اجرای همه‌ی مراحل — هم از سرور و هم از `npm run seed` قابل صدا زدن است */
function seedAll() {
  const catalog = seedCatalog();
  const admin = seedAdmin();
  seedSettings();
  seedTestimonials();
  return { catalog, admin };
}

