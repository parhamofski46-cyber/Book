/**
 * مدل‌های گل فرفورژه از کاتالوگ واقعی انبار می‌آیند.
 *
 * فایل src/content/forge-models.json با اسکریپت
 * scripts/extract-forge-catalog.py از روی کاتالوگ PDF ساخته شده و برای هر
 * مدل کد، ابعاد تصویر و — در بیشتر موارد — اندازه و وزن واقعی را دارد.
 * تصویر هر مدل در public/img/forge/<کد>.webp است.
 *
 * چرا فقط کد و نه اسم: انبار صدها مدل دارد و هیچ‌کدام اسم توصیفی ندارند.
 * مشتری به عکس نگاه می‌کند و کد را می‌گوید. اسم ساختگی گذاشتن، هم برای
 * فروشنده بی‌معنی بود هم مشتری را وادار می‌کرد چیزی را حفظ کند که در انبار
 * به کار نمی‌رود.
 */
const FORGE_CATALOG = require('../content/forge-models.json');

const forgeModels = () =>
  FORGE_CATALOG.map((m) => {
    const code = toFaDigits(m.code);
    const specs = [];
    if (m.size) specs.push(`اندازه ${toFaDigits(m.size.replace('x', '×'))} سانتی‌متر`);
    if (m.weight) specs.push(`وزن حدود ${toFaDigits(m.weight)} کیلوگرم`);

    return {
      name: `کد ${code}`,
      // خلاصه فقط وقتی نوشته می‌شود که واقعاً اطلاعاتی داشته باشیم؛
      // کارت باید تمیز بماند و چیزی جز کد و عکس به مشتری تحمیل نکند.
      summary: m.size ? toFaDigits(m.size.replace('x', '×')) + ' سانتی‌متر' : '',
      unit: 'عدد',
      description:
        `گل آماده‌ی فرفورژه، کد ${code}.` +
        (specs.length ? ` ${specs.join('، ')}.` : '') +
        '\n\nقطعه در انبار موجود است و آماده‌ی تحویل. برای درب، پنجره، نرده و ' +
        'حفاظ استفاده می‌شود.\n\nقطعه را تحویل می‌گیرید و جوشکار خودتان روی کار ' +
        'نصبش می‌کند — ما کار نصب انجام نمی‌دهیم.\n\nبرای دیدن حضوری مدل‌ها به ' +
        'انبار ما در علی‌آباد کتول سر بزنید، یا کد موردنظرتان را در واتساپ بفرستید.',
    };
  });

