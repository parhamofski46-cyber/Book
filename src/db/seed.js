const insertCategory = db.prepare(
  'INSERT INTO categories (slug, name, description, sort_order, is_featured) VALUES (?, ?, ?, ?, ?)'
);
const insertSubcategory = db.prepare(
  'INSERT INTO subcategories (category_id, slug, name, sort_order) VALUES (?, ?, ?, ?)'
);
const insertProduct = db.prepare(
  `INSERT INTO products (slug, name, category_id, subcategory_id, summary, description,
                         price_text, unit, in_stock, sort_order)
   VALUES (@slug, @name, @category_id, @subcategory_id, @summary, @description,
           @price_text, @unit, 1, @sort_order)`
);

/** درج یک دسته به‌همراه زیردسته‌ها و محصولاتش */
function insertCategoryTree(cat, ci) {
  const catSlug = slugify(cat.name);
  const { lastInsertRowid: catId } = insertCategory.run(
    catSlug,
    cat.name,
    cat.description,
    ci,
    cat.featured || 0
  );

  const subIds = {};
  (cat.subcategories || []).forEach((sub, si) => {
    const { lastInsertRowid: subId } = insertSubcategory.run(catId, slugify(sub.name), sub.name, si);
    subIds[sub.name] = subId;
  });

  (cat.products || []).forEach((p, pi) => {
    insertProduct.run({
      slug: uniqueSlug(
        slugify(p.name),
        (s) => !!db.prepare('SELECT 1 FROM products WHERE slug = ?').get(s)
      ),
      name: p.name,
      category_id: catId,
      subcategory_id: p.sub ? subIds[p.sub] || null : null,
      summary: p.summary || '',
      description: p.description || '',
      price_text: 'استعلام قیمت روز',
      unit: p.unit || '',
      sort_order: pi,
    });
  });
}

/**
 * افزودن چیزهایی که در نسخه‌های بعدی به فهرست اضافه شده‌اند — دسته‌ی جدید،
 * زیردسته‌ی جدید و محصول جدیدِ داخل دسته‌های موجود.
 *
 * فقط یک‌بار به‌ازای هر نسخه اجرا می‌شود (کلید catalog_version) تا اگر مدیر
 * چیزی را عمداً حذف کرده باشد، با هر ری‌استارت دوباره برنگردد.
 *
 * ⚠️ این تابع فقط **اضافه** می‌کند و هرگز چیزی را بازنویسی یا حذف نمی‌کند؛
 * پس اگر مدیر نام یا توضیح محصولی را از پنل عوض کرده باشد، دست‌نخورده
 * می‌ماند. تشخیص «هست یا نیست» بر اساس اسلاگ است.
 */
const CATALOG_VERSION = '9';

function migrateCatalog() {
  if (getSetting('catalog_version') === CATALOG_VERSION) return false;

  const existing = db.prepare('SELECT COUNT(*) n FROM categories').get().n;
  if (existing === 0) return false; // دیتابیس خالی است؛ seedCatalog خودش همه را می‌سازد

  const findCat = db.prepare('SELECT id FROM categories WHERE slug = ?');
  const findSub = db.prepare('SELECT id FROM subcategories WHERE category_id = ? AND slug = ?');
  const findProd = db.prepare('SELECT id, subcategory_id FROM products WHERE slug = ?');
  const setProdSub = db.prepare('UPDATE products SET subcategory_id = ? WHERE id = ?');
  const maxSort = db.prepare(
    'SELECT COALESCE(MAX(sort_order), -1) n FROM products WHERE category_id = ?'
  );

  let addedCats = 0;
  let addedSubs = 0;
  let addedProds = 0;
  let linkedSubs = 0;

  const run = db.transaction(() => {
    CATEGORIES.forEach((cat, ci) => {
      const catSlug = slugify(cat.name);
      const row = findCat.get(catSlug);

      // دسته‌ی کاملاً جدید: همه‌ی درختش یک‌جا ساخته می‌شود
      if (!row) {
        insertCategoryTree(cat, ci);
        addedCats += 1;
        return;
      }

      // دسته هست — زیردسته‌ها و محصولات جانمانده را اضافه کن
      const catId = row.id;
      const subIds = {};
      (cat.subcategories || []).forEach((sub, si) => {
        const subSlug = slugify(sub.name);
        const found = findSub.get(catId, subSlug);
        if (found) {
          subIds[sub.name] = found.id;
        } else {
          const { lastInsertRowid } = insertSubcategory.run(catId, subSlug, sub.name, si);
          subIds[sub.name] = lastInsertRowid;
          addedSubs += 1;
        }
      });

      let sort = maxSort.get(catId).n;
      (cat.products || []).forEach((p) => {
        const prodSlug = slugify(p.name);
        const found = findProd.get(prodSlug);
        if (found) {
          // محصول از قبل هست. تنها کاری که می‌کنیم: اگر زیردسته‌اش خالی است و
          // در فهرست برایش زیردسته تعریف شده، همان را پر می‌کنیم. این حالت
          // وقتی پیش می‌آید که دسته‌ای بعداً زیردسته‌بندی شود (مثل قوطی که
          // اول بدون زیردسته بود و بعد مربع/مستطیل گرفت). چیزی بازنویسی
          // نمی‌شود، فقط جای خالی پر می‌گردد.
          if (p.sub && subIds[p.sub] && found.subcategory_id == null) {
            setProdSub.run(subIds[p.sub], found.id);
            linkedSubs += 1;
          }
          return;
        }
        sort += 1;
        insertProduct.run({
          slug: prodSlug,
          name: p.name,
          category_id: catId,
          subcategory_id: p.sub ? subIds[p.sub] || null : null,
          summary: p.summary || '',
          description: p.description || '',
          price_text: 'استعلام قیمت روز',
          unit: p.unit || '',
          sort_order: sort,
        });
        addedProds += 1;
      });
    });

    // «کاتالوگ کامل ۶۰۰ مدل» یک مدل نیست، یک دعوت است — باید ته گالری
    // بنشیند. اینجا انجام می‌شود نه در fixContent، چون محصولات جدید بعد از
    // بیشترین sort_order اضافه می‌شوند و هر مقداری که زودتر تنظیم شود را
    // پشت سر می‌گذارند.
    const catalogRow = db
      .prepare("SELECT id, category_id FROM products WHERE name = 'کاتالوگ کامل ۶۰۰ مدل فرفورژه'")
      .get();
    if (catalogRow) {
      const top = db
        .prepare('SELECT COALESCE(MAX(sort_order), 0) n FROM products WHERE category_id = ?')
        .get(catalogRow.category_id).n;
      db.prepare('UPDATE products SET sort_order = ? WHERE id = ?').run(top + 1, catalogRow.id);
    }
  });
  run();

  setSetting('catalog_version', CATALOG_VERSION);
  return {
    categories: addedCats,
    subcategories: addedSubs,
    products: addedProds,
    linked: linkedSubs,
  };
}

/**
 * اصلاح‌های محتوایی که بعد از راه‌اندازی اولیه لازم شدند.
 * فقط یک‌بار اجرا می‌شود (بر اساس content_fixes_version) تا اگر مدیر بعداً
 * دستی چیزی را عوض کرد، دوباره بازنویسی نشود.
 */
const CONTENT_FIX_VERSION = '10';

function fixContent() {
  if (getSetting('content_fixes_version') === CONTENT_FIX_VERSION) return false;

  const run = db.transaction(() => {
    // ترتیب سایزهای قوطی. وقتی سایزهای جدید به دسته‌ی موجود اضافه شدند، ته
    // فهرست چسبیدند و ترتیب نمایش به‌هم ریخت (۲۰، ۴۰، ۶۰، بعد ۳۰، ۵۰ …).
    // اینجا بر اساس ترتیب جدول GHOUTI_SIZES دوباره شماره‌گذاری می‌شوند تا
    // منوی انتخاب سایز صعودی و قابل‌پیش‌بینی باشد.
    const setSort = db.prepare('UPDATE products SET sort_order = ? WHERE slug = ?');
    let gi = 0;
    Object.values(GHOUTI_SIZES)
      .flat()
      .forEach(([size]) => setSort.run(gi++, slugify(`قوطی ${size}`)));

    // زیرنویس هیرو برای سئو («آهن‌فروشی گرگان»، «فروش قوطی و پروفیل») — فقط
    // اگر هنوز مقدار پیش‌فرض قدیمی است دست می‌زنیم، تا متن سفارشی‌شده‌ی
    // مدیر از پنل پاک نشود.
    db.prepare(
      `UPDATE settings SET value = 'آهن‌فروشی گرگان و علی‌آباد کتول — فروش قوطی و پروفیل و تولید ورق گالوانیزه'
       WHERE key = 'hero_subtitle' AND value = 'تأمین‌کننده‌ی مصالح فلزی و فرفورژه در علی‌آباد کتول و گرگان'`
    ).run();

    // املای «رابیس» به «رابیتس» تغییر کرد (خواسته‌ی مالک).
    // اسلاگ‌ها هم عوض می‌شوند، پس آدرس دسته و محصول‌ها تغییر می‌کند؛
    // برای اینکه لینک‌های قدیمی و نتایج گوگل نشکنند، در
    // `src/routes/public.js` هر آدرسی که «رابیس» دارد با ۳۰۱ به نسخه‌ی
    // «رابیتس» منتقل می‌شود. آن قانون را حذف نکن.
    const ren = (table, col) =>
      db.prepare(`UPDATE ${table} SET ${col} = REPLACE(${col}, 'رابیس', 'رابیتس') WHERE ${col} LIKE '%رابیس%'`).run();
    ren('categories', 'name');
    ren('categories', 'slug');
    ren('products', 'slug');
    ren('categories', 'description');
    ren('products', 'name');
    ren('products', 'summary');
    ren('products', 'description');
    ren('testimonials', 'text');
    // در توضیح دسته، هر دو املا بماند تا با هر دو جست‌وجو پیدا شود
    db.prepare(
      "UPDATE categories SET description = 'رابیتس (رابیس) گچ‌کاری و نماکاری در وزن‌ها و تعداد ستون‌های مختلف' WHERE name = 'رابیتس'"
    ).run();

    // شمار مدل‌های فرفورژه از ۱۰۰۰ به ۶۰۰ اصلاح شد (عدد واقعی انبار).
    // فقط جایی عوض می‌شود که «۱۰۰۰ مدل» باشد، تا سایز محصولی مثل
    // «قوطی ۱۰۰×۱۰۰» تصادفی دستکاری نشود.
    const fixCount = (table, col) =>
      db.prepare(
        `UPDATE ${table} SET ${col} = REPLACE(${col}, '۱۰۰۰ مدل', '۶۰۰ مدل') WHERE ${col} LIKE '%۱۰۰۰ مدل%'`
      ).run();
    fixCount('settings', 'value');
    fixCount('categories', 'description');
    fixCount('products', 'description');
    fixCount('products', 'summary');
    db.prepare("UPDATE settings SET value = '۶۰۰' WHERE key = 'stat_models' AND value = '۱۰۰۰'").run();
    // نام و اسلاگ محصول کاتالوگ هم عوض می‌شود. این باید قبل از
    // migrateCatalog اتفاق بیفتد، وگرنه آن، نامِ تازه را «نبود» می‌بیند و
    // یک محصول تکراری می‌سازد.
    db.prepare(
      `UPDATE products SET name = 'کاتالوگ کامل ۶۰۰ مدل فرفورژه', slug = ?
       WHERE name = 'کاتالوگ کامل ۱۰۰۰ مدل فرفورژه'`
    ).run(slugify('کاتالوگ کامل ۶۰۰ مدل فرفورژه'));

    // «فوم عایق» یک محصول کلی بود؛ حالا سه ضخامت مشخص (۱، ۱.۵ و ۲ سانت)
    // جایگزینش شده‌اند که همان چیزی است که در انبار هست.
    db.prepare("DELETE FROM products WHERE name = 'فوم عایق'").run();

    // شاخ گوزنی فقط یک مدل دارد: ارتفاع ۹۰ سانتی‌متر با جوش CO2.
    // سه مدل قبلی (سه‌شاخه، دوشاخه، گالوانیزه) در انبار موجود نیستند و
    // نگه‌داشتنشان یعنی مشتری چیزی سفارش بدهد که نداریم.
    ['شاخ گوزنی سه‌شاخه', 'شاخ گوزنی دوشاخه', 'شاخ گوزنی گالوانیزه'].forEach((n) =>
      db.prepare('DELETE FROM products WHERE name = ?').run(n)
    );
    db.prepare(
      "UPDATE categories SET description = 'شاخ گوزنی حفاظ دیوار، ارتفاع ۹۰ سانتی‌متر با جوش CO2' WHERE name = 'شاخ گوزنی'"
    ).run();

    // مدل‌های جایگزینِ موقت (کد ۱۰۱ تا ۱۱۲) که تصویرسازی دستی داشتند، حالا
    // که کاتالوگ واقعی انبار وارد شده حذف می‌شوند. آن‌ها فقط برای این ساخته
    // شده بودند که بخش فرفورژه بدون عکس نماند.
    const placeholderCodes = [];
    for (let i = 101; i <= 112; i++) placeholderCodes.push(`کد ${toFaDigits(i)}`);
    const delPlaceholder = db.prepare('DELETE FROM products WHERE name = ?');
    placeholderCodes.forEach((n) => delPlaceholder.run(n));

    // بازسازی بخش فرفورژه: از «نام توصیفی» به «کد مدل».
    // محصولات قدیمی با نام مشخص حذف می‌شوند (فهرست صریح، تا محصولی که مدیر
    // خودش اضافه کرده دست‌نخورده بماند)، و سه زیردسته‌ی ساختگی هم برداشته
    // می‌شوند تا این بخش یک گالری یکپارچه شود.
    const oldForge = [
      'گل فرفورژه طرح پیچک',
      'گل فرفورژه طرح شاخه و برگ',
      'گل حلزونی ساده',
      'ست طرح درب حیاط کلاسیک',
      'گل درب طرح خورشیدی',
      'گل حفاظ پنجره طرح لاله',
      'گل حفاظ پنجره مدل حلزونی',
      'گل حفاظ پنجره طرح شاخ گوزنی',
    ];
    const delProd = db.prepare('DELETE FROM products WHERE name = ?');
    oldForge.forEach((n) => delProd.run(n));

    const forgeCat = db
      .prepare('SELECT id FROM categories WHERE slug = ?')
      .get(slugify('گل و طرح‌های فرفورژه'));
    if (forgeCat) {
      // محصولات باقی‌مانده از زیردسته جدا می‌شوند تا حذف زیردسته چیزی را نبرد
      db.prepare('UPDATE products SET subcategory_id = NULL WHERE category_id = ?').run(forgeCat.id);
      db.prepare(
        "DELETE FROM subcategories WHERE category_id = ? AND name IN ('طرح نرده','طرح درب','طرح پنجره')"
      ).run(forgeCat.id);
    }

    // حذف نظرهای ساختگی «(نمونه)» از دیتابیس‌هایی که قبلاً ساخته شده‌اند.
    // فقط رکوردهایی که برچسب «(نمونه)» دارند حذف می‌شوند، پس اگر مدیر نظر
    // واقعی ثبت کرده باشد دست‌نخورده می‌ماند.
    db.prepare("DELETE FROM testimonials WHERE name LIKE '(نمونه)%'").run();

    // ورق گالوانیزه: فقط ضخامت ۰.۵، دو طرح
    db.prepare("DELETE FROM products WHERE name = 'ورق شیروانی سفارشی'").run();
    db.prepare("UPDATE subcategories SET name = 'طرح سفال' WHERE name = 'طرح سفال رنگی'").run();
    db.prepare("UPDATE subcategories SET name = 'طرح گالوانیزه' WHERE name = 'گالوانیزه شفاف'").run();
    db.prepare("UPDATE products SET name = 'ورق گالوانیزه طرح سفال' WHERE name = 'ورق گالوانیزه طرح سفال رنگی'").run();
    db.prepare("UPDATE products SET name = 'ورق گالوانیزه طرح گالوانیزه' WHERE name = 'ورق گالوانیزه شفاف'").run();
  });
  run();

  setSetting('content_fixes_version', CONTENT_FIX_VERSION);
  return true;
}

function seedCatalog() {
  const already = db.prepare('SELECT COUNT(*) n FROM categories').get().n;
  if (already > 0) return false; // قبلاً پر شده — دست نمی‌زنیم

  const run = db.transaction(() => {
    CATEGORIES.forEach((cat, ci) => {
      const catSlug = slugify(cat.name);
      const { lastInsertRowid: catId } = insertCategory.run(
        catSlug,
        cat.name,
        cat.description,
        ci,
        cat.featured || 0
      );

      const subIds = {};
      (cat.subcategories || []).forEach((sub, si) => {
        const { lastInsertRowid: subId } = insertSubcategory.run(
          catId,
          slugify(sub.name),
          sub.name,
          si
        );
        subIds[sub.name] = subId;
      });

      (cat.products || []).forEach((p, pi) => {
        insertProduct.run({
          slug: slugify(p.name),
          name: p.name,
          category_id: catId,
          subcategory_id: p.sub ? subIds[p.sub] || null : null,
          summary: p.summary || '',
          description: p.description || '',
          price_text: 'استعلام قیمت روز',
          unit: p.unit || '',
          sort_order: pi,
        });
      });
    });
  });

  run();
  setSetting('catalog_version', CATALOG_VERSION);
  return true;
}

// ------------------------------------------------- کاربر پیش‌فرض پنل

function seedAdmin() {
  const exists = db.prepare('SELECT COUNT(*) n FROM admins').get().n;
  if (exists > 0) return null;

  const username = process.env.ADMIN_USERNAME || 'admin';
  const password = process.env.ADMIN_PASSWORD || 'foolad1234';
  const mustChange = process.env.ADMIN_PASSWORD ? 0 : 1;

  db.prepare('INSERT INTO admins (username, password_hash, must_change) VALUES (?, ?, ?)').run(
    username,
    bcrypt.hashSync(password, 12),
    mustChange
  );

  return { username, password, mustChange };
}

